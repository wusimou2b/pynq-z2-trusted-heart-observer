const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const original=path.join(__dirname,'public_live_release/runtime/continuous_client.js');
const control=require(fs.existsSync(original)?original:path.join(__dirname,'../runtime/continuous_client.js'));
assert.equal(typeof control.contentPath,'function','public notebook-relative control path is not implemented');
const options={controlPath:'runtime/continuous-control',relativeToNotebook:true};
assert.equal(control.contentPath(options,'project/PublicLive.ipynb'),'project/runtime/continuous-control');
assert.equal(control.contentPath(options,'nested/project/PublicLive.ipynb'),'nested/project/runtime/continuous-control');
assert.equal(control.contentPath(options,'PublicLive.ipynb'),'runtime/continuous-control');
assert.equal(control.contentPath({controlPath:'old-root/continuous-control'},'project/Old.ipynb'),'old-root/continuous-control');
assert.throws(()=>control.contentPath({controlPath:'../escape',relativeToNotebook:true},'project/PublicLive.ipynb'));
assert.throws(()=>control.contentPath(options,'../project/PublicLive.ipynb'));
console.log('6 public/legacy control-path assertions passed; no browser or hardware used');
